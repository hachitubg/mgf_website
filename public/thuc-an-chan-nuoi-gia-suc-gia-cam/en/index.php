                        form.find('#contact_productType').replaceWith($(repo.php).find('#contact_productType'))
                        form.find('#contact_product').replaceWith($(repo.php).find('#contact_product'))

                        $('#product-detail-modal').modal('hide');
                        if (form) {
                            document.querySelector('#form-contact').scrollIntoView({behavior: 'smooth'});
                        }
                    }
                })
            });

            /**
             * Change productType on form contact
             */
            body.on('change','#contact_productType',function(e) {
                const element = $(e.currentTarget)
                let data = {}
                data[form.find('#contact_productType').attr('name')] = element.val()
                data[form.find('#contact__token').attr('name')] = form.find('#contact__token').val()
                data['inserted'] = false

                $.ajax({
                    url: 'https://www.greenfeed.com.vn/thuc-an-chan-nuoi-gia-suc-gia-cam/en/handle/contact-form',
                    data: data,
                    method: 'POST',
                    success: jsonData => {
                        form.find('#contact_product').replaceWith($(JSON.parse(jsonData).php).find('#contact_product'))
                    }
                });
            });

            body.on('change','#contact_city',function(e){
                e.preventDefault();
                let data = {};
                data[$(this).attr('name')] = $(this).val();
                data[form.find('#contact__token').attr('name')] = form.find('#contact__token').val();
                data['inserted'] = false;
                $.ajax({
                    url: 'https://www.greenfeed.com.vn/thuc-an-chan-nuoi-gia-suc-gia-cam/en/handle/contact-form',
                    data: data,
                    method: 'POST',
                    success: jsonData => {
                        form.find('#contact_district').replaceWith($(JSON.parse(jsonData).php).find('#contact_district'));
                    }
                })
            })

            /**
             * submit form contact
             * @type {*|jQuery|HTMLElement}
             */
            form.submit(e => {
                e.preventDefault()
                $(form).ajaxSubmit({
                    success: jsonData => {
                        const repo = JSON.parse(jsonData);
                        form.find('#contact__token').replaceWith($(repo.php).find('#contact__token'));
                        $('#success').replaceWith($(repo.phpSuccess));
                        $('#success').modal('show');
                        form.find(".form-control").val('');
                        form.find(".form-select").val('');
                        form.find("#contact_district").php(`<option value="" selected="selected">Quận huyện</option>`);
                        $('.success .btn').on('click', function(e){
                            $('#success').modal('hide');
                        });
                    },
                    error:  jsonData => {
                        console.error(jsonData.responseText)
                    }
                })
            })

